const fs = require('fs');
const vm = require('vm');
const assert = require('assert');
const context = {};
vm.createContext(context);
vm.runInContext(fs.readFileSync('frontend/static/js/app.js', 'utf8'), context);
const app = vm.runInContext('platform()', context);
const straight = { folder: 'Straight', name: 'TH12_001', simulation_type: 1, result: { mean_Cla: '1' } };
const corner = { folder: 'Cornering', name: 'TH12_001', simulation_type: 3, result: { mean_Cla: '2' } };
app.cases = [straight, corner];
assert.notStrictEqual(app.caseKey(straight), app.caseKey(corner));
assert.strictEqual(app.caseLabel(app.caseKey(corner)), 'Cornering / TH12_001');
app.resetViewerState = () => {};
app.toggleSelect(app.caseKey(straight));
app.loadAsMain();
app.toggleSelect(app.caseKey(corner));
app.loadAsSub();
assert.strictEqual(app.mainCase, app.caseKey(straight));
assert.strictEqual(app.subCase, app.caseKey(corner));
assert.strictEqual(app.caseResultValue({case_name: 'TH12_001', simulation_type: 3}, 'mean_Cla'), '2');
assert.strictEqual(app.caseResultValue({case_name: 'TH12_001', simulation_type: 1}, 'mean_Cla'), '1');
console.log('case selection and job result identity: OK');
